def sitemap(inv):
    path = os.path.join(ROOT, 'sitemap.xml'); old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    static = [m for m in re.findall(r'<url>.*?</url>', old, flags=re.S) if '/watches/' not in m]
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'] + ['  ' + s.strip() for s in static]
    for w in sorted(inv['watches'], key=lambda x: x['slug']):
        lm = f'<lastmod>{E(w["updated"])}</lastmod>' if re.match(r'^\d{4}-\d{2}-\d{2}$', w.get('updated') or '') else ''
        lines.append(f'  <url><loc>{SITE}/watches/{E(w["slug"])}/</loc>{lm}</url>')
    lines.append('</urlset>')
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')


def main():
    inv, tpl = load(); head, header, footer = split_template(tpl)
    out_dir = os.path.join(ROOT, 'watches'); os.makedirs(out_dir, exist_ok=True); keep = set()
    for w in inv['watches']:
        if not re.match(r'^[a-z0-9][a-z0-9-]*$', w.get('slug') or ''): print('skip bad slug', w.get('slug')); continue
        keep.add(w['slug']); d = os.path.join(out_dir, w['slug']); os.makedirs(d, exist_ok=True)
        html_ = page(w, inv, head, header, footer); p = os.path.join(d, 'index.html')
        if not os.path.exists(p) or open(p, encoding='utf-8').read() != html_: open(p, 'w', encoding='utf-8').write(html_)
    for s in os.listdir(out_dir):
        p = os.path.join(out_dir, s, 'index.html')
        if s not in keep and os.path.isfile(p) and MARK in open(p, encoding='utf-8').read(): shutil.rmtree(os.path.join(out_dir, s))
    sitemap(inv)
    print(f'{len(keep)} watch pages, sitemap with {len(keep)} watch URLs')


if __name__ == '__main__':
    main()
