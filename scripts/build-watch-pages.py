    spec = ''.join(f'<tr><th>{E(k)}</th><td>{E(v)}</td></tr>' for k, v in rows if v)
    main_img = f'<img id="dImg" src="/{E(pics[0])}" alt="{E(full(w))}">' if pics else ''
